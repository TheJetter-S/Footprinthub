import uuid

from sqlalchemy import String, Text, ForeignKey
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin


def _new_uuid() -> str:
    return str(uuid.uuid4())


class Finding(Base, TimestampMixin):
    """
    A security finding generated by a module.
    Each finding has a severity level, description, and remediation advice.
    """

    __tablename__ = "findings"

    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=_new_uuid
    )
    scan_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("scans.id", ondelete="CASCADE"),
        nullable=False, index=True
    )
    module_name: Mapped[str] = mapped_column(
        String(50), nullable=False, index=True,
        comment="Module that generated this finding"
    )
    severity: Mapped[str] = mapped_column(
        String(10), nullable=False, index=True,
        comment="Severity: critical | high | medium | low | info"
    )
    title: Mapped[str] = mapped_column(
        String(500), nullable=False,
        comment="Short finding title"
    )
    description: Mapped[str] = mapped_column(
        Text, nullable=False,
        comment="Detailed explanation of the finding"
    )
    remediation: Mapped[str] = mapped_column(
        Text, nullable=True,
        comment="Recommended remediation steps"
    )

    # Relationships
    scan = relationship("Scan", back_populates="findings")

    def __repr__(self) -> str:
        return f"<Finding [{self.severity}] {self.title[:40]}>"
